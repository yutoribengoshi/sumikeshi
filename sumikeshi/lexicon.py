def kata_generic(tok: str) -> bool:
    """カナ語が一般語の連結だけでできているか（チェック＋リスト は一般語、ハイエスト＋ホーム は違う）。"""
    tok = tok.replace("・", "")
    n = len(tok)
    if n == 0:
        return True
    ok = [False] * (n + 1)
    ok[0] = True
    for i in range(n):
        if not ok[i]:
            continue
        for j in range(i + 2, min(n, i + 16) + 1):
            if tok[i:j] in KATA_GENERIC:
                ok[j] = True
    return ok[n]


