def _build_variants() -> dict[str, set[str]]:
    eq: dict[str, set[str]] = {}

    def link(a: str, b: str) -> None:
        group = eq.get(a, {a}) | eq.get(b, {b})
        for ch in group:
            eq[ch] = group

    for g in _VARIANT_GROUPS:
        for ch in g[1:]:
            link(g[0], ch)
    # 互換漢字（U+F900–FAFF）は NFKC で統合漢字に寄る。逆向きも引けるように両方を結ぶ
    for cp in range(0xF900, 0xFB00):
        ch = chr(cp)
        n = unicodedata.normalize("NFKC", ch)
        if n != ch and len(n) == 1:
            link(n, ch)
    # 英数字の全角・半角（大文字と小文字は別の字。「b3」と記号の「Ｂ３」を同じにしない）
    for a, b in zip("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "ＡＢＣＤＥＦＧＨＩＪＫＬＭＮＯＰＱＲＳＴＵＶＷＸＹＺ"):
        link(a, b)
        link(a.lower(), chr(ord(b) + 0x20))
    for a, b in zip("0123456789", "０１２３４５６７８９"):
        link(a, b)
    for a, b in (("&", "＆"), ("・", "･"), ("-", "－")):
        link(a, b)
    return eq


VARIANTS = _build_variants()


def nfkc_name(s: str) -> str:
    """照合用の正規化（空白を除き、異体字を代表字に寄せる）。"""
    out = []
    for ch in s:
        if ch in SPACE_SET:
            continue
        group = VARIANTS.get(ch)
        out.append(min(group) if group else ch)
    return "".join(out)
